  tr(`${Math.floor(days / 7)}+${days % 7} 周`, `${Math.floor(days / 7)}+${days % 7} wk`);

function erf(x: number) {
  const sign = x < 0 ? -1 : 1;
  const a = Math.abs(x);
  const t = 1 / (1 + 0.3275911 * a);
  const y =
    1 -
    ((((1.061405429 * t - 1.453152027) * t + 1.421413741) * t - 0.284496736) * t + 0.254829592) *
      t *
      Math.exp(-a * a);
  return sign * y;
}
function normalCdf(z: number) {
  return 0.5 * (1 + erf(z / Math.SQRT2));
}

export function zScore(metric: GrowthMetric, sex: BabySex, months: number, value: number) {
  if (months < 0 || months > 60) return null;
  const table = standards[metric][sex];
  const lo = Math.floor(months);
  const hi = Math.ceil(months);
  const ratio = months - lo;
  const low = table[lo],
    high = table[hi];
  const l = low[1] + (high[1] - low[1]) * ratio,
    m = low[2] + (high[2] - low[2]) * ratio,
    s = low[3] + (high[3] - low[3]) * ratio;
  return Math.abs(l) < 1e-8 ? Math.log(value / m) / s : (Math.pow(value / m, l) - 1) / (l * s);
}
export function growthPercentile(metric: GrowthMetric, sex: BabySex, months: number, value: number) {
  const z = zScore(metric, sex, months, value);
  return z === null ? null : Math.max(0.1, Math.min(99.9, normalCdf(z) * 100));
}
export function percentileLabel(value: number) {
  if (value < 1) return '< P1';
  if (value > 99) return '> P99';
  return `P${Math.round(value)}`;
}

// The five lines drawn on the chart (P3, P15, P50, P85, P97) as z-scores.
const MAJOR_LINES = [-1.881, -1.036, 0, 1.036, 1.881];
const MAJOR_LABELS = ['P3', 'P15', 'P50', 'P85', 'P97'];
const band = (z: number) => MAJOR_LINES.filter(line => z > line).length;
export type GrowthDrift = {
  metric: GrowthMetric;
  direction: 'down' | 'up';
  from: string;
  to: string;
  fromDate: string;
  toDate: string;
};
/**
 * Flags when the latest measurement has crossed two or more major percentile lines compared with
 * the highest (or, for head size, also the lowest) position in the preceding six months.
 * Measurements from the first two weeks are ignored because newborn weight loss is expected.
 */
export function percentileDrift(
  metric: GrowthMetric,
  points: {months: number; z: number; date: string}[],
): GrowthDrift | null {
  const usable = points.filter(p => p.months >= 0.5).sort((a, b) => a.date.localeCompare(b.date));
  if (usable.length < 2) return null;
  const latest = usable[usable.length - 1];
  const window = usable.slice(0, -1).filter(p => p.months >= latest.months - 6);
  if (!window.length) return null;
  const now = band(latest.z);
  const high = window.reduce((a, b) => (band(b.z) > band(a.z) ? b : a));
  const label = (z: number) => {
    const b = band(z);
    return b === 0
      ? tr('P3 以下', 'below P3')
      : b === 5
        ? tr('P97 以上', 'above P97')
        : `${MAJOR_LABELS[b - 1]}–${MAJOR_LABELS[b]}`;
  };
  if (band(high.z) - now >= 2)
    return {
      metric,
      direction: 'down',
      from: label(high.z),
      to: label(latest.z),
      fromDate: high.date,
      toDate: latest.date,
    };
  if (metric === 'head') {
    const low = window.reduce((a, b) => (band(b.z) < band(a.z) ? b : a));
    if (now - band(low.z) >= 2)
      return {
        metric,
        direction: 'up',
        from: label(low.z),
        to: label(latest.z),
        fromDate: low.date,
        toDate: latest.date,
      };
  }
  return null;
}
